"""Alembic の変更履歴のテスト（テスト一覧 #1〜#3）。

ほかのテストと別の DB（ecu_sec_test_migrations）で、適用・取り消しをくり返す。
"""

from collections.abc import Iterator

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import URL, create_engine, inspect, text

from tests.conftest import TEST_DB, alembic_config, recreate_test_database

TABLES = {
    "companies",
    "users",
    "ecus",
    "measure_items",
    "assessments",
    "assessment_entries",
    "audit_logs",
    "comments",
    "comment_reads",
}


@pytest.fixture(scope="module")
def migrations_url() -> Iterator[URL]:
    yield recreate_test_database(f"{TEST_DB}_migrations")


def table_names(url: URL) -> set[str]:
    eng = create_engine(url)
    try:
        return set(inspect(eng).get_table_names()) - {"alembic_version"}
    finally:
        eng.dispose()


# docs/spec.md「データ（テーブル）」の列（このほかに作成日時などがあってもよい）
SPEC_COLUMNS = {
    "companies": {"id", "name", "type"},
    "users": {"id", "company_id", "email", "password_hash", "role", "is_active"},
    "ecus": {"id", "supplier_id", "name", "part_no", "vehicle_model"},
    "measure_items": {"id", "code", "title", "description", "sort_order"},
    "assessments": {
        "id",
        "ecu_id",
        "version",
        "status",
        "submitted_by",
        "approved_by",
        "submitted_at",
        "approved_at",
        "reject_reason",
        "review_status",
        "reviewed_by",
        "reviewed_at",
    },
    "assessment_entries": {"id", "assessment_id", "item_id", "status", "evidence", "planned_date"},
    "audit_logs": {"id", "user_id", "action", "target", "ip", "created_at"},
    "comments": {
        "id",
        "assessment_id",
        "item_id",
        "parent_id",
        "author_id",
        "kind",
        "body",
        "created_at",
    },
    "comment_reads": {"user_id", "comment_id", "read_at"},
}


def test_upgrade_head_creates_all_tables(migrations_url: URL) -> None:
    command.upgrade(alembic_config(migrations_url), "head")
    assert table_names(migrations_url) == TABLES
    eng = create_engine(migrations_url)
    try:
        insp = inspect(eng)
        for table, columns in SPEC_COLUMNS.items():
            actual = {c["name"] for c in insp.get_columns(table)}
            assert columns <= actual, f"{table} に仕様の列がない：{columns - actual}"
    finally:
        eng.dispose()


def test_all_foreign_keys_restrict_delete(migrations_url: URL) -> None:
    """外部キーの「消そうとしたら」の動きが、すべて RESTRICT（'r'）であること。
    既定の NO ACTION（'a'）も消すと失敗するので、動きの試しでは区別できない。
    DB の定義で確かめる。"""
    command.upgrade(alembic_config(migrations_url), "head")
    eng = create_engine(migrations_url)
    try:
        with eng.connect() as conn:
            rows = conn.execute(
                text("SELECT conname, confdeltype FROM pg_constraint WHERE contype = 'f'")
            ).all()
    finally:
        eng.dispose()
    assert rows, "外部キーが1つもない"
    assert {name for name, kind in rows if kind != "r"} == set()


def test_downgrade_base_then_upgrade_again(migrations_url: URL) -> None:
    cfg = alembic_config(migrations_url)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    assert table_names(migrations_url) == set()
    command.upgrade(cfg, "head")
    assert table_names(migrations_url) == TABLES


def test_models_match_migrations(migrations_url: URL) -> None:
    """モデル（app/models.py）を変えたのに変更履歴を足し忘れると落ちる。"""
    cfg = alembic_config(migrations_url)
    command.upgrade(cfg, "head")
    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as e:  # 差の中身を表示して落とす
        pytest.fail(f"モデルと変更履歴に差がある：{e}")
